def cluster_feats(rgb, mode="grabcut", k=3):
    m = garment_mask(rgb, mode)
    lab = cv2.cvtColor(rgb, cv2.COLOR_RGB2LAB)[m].astype(np.float32)
    if len(lab) > 4000:
        lab = lab[np.random.RandomState(0).choice(len(lab), 4000, replace=False)]
    k = max(1, min(k, len(lab)))
    _, lbl, cen = cv2.kmeans(lab, k, None,
                             (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 20, 1.0),
                             3, cv2.KMEANS_PP_CENTERS)
    share = np.bincount(lbl.ravel(), minlength=k) / len(lbl)
    o = np.argsort(-share); cen, share = cen[o], share[o]
    while len(share) < 3:                          # pad to 3 clusters
        cen = np.vstack([cen, cen[0]]); share = np.append(share, 0.0)
    return np.concatenate([np.c_[cen, share].ravel(), [m.mean()]])   # 3x(L,a,b,share) + mask fraction

