def as_tensor(x):
    return x if torch.is_tensor(x) else x.pooler_output

@torch.no_grad()
def text_features():
    feats = []
    for c in classes:
        prompts = [t.format(PROMPT_NAME[c]) for t in TEMPLATES]
        inp = processor(text=prompts, return_tensors="pt", padding=True).to(device)
        f = as_tensor(model.get_text_features(**inp))
        f = f / f.norm(dim=-1, keepdim=True)
        f = f.mean(dim=0); f = f / f.norm()
        feats.append(f)
    return torch.stack(feats)

