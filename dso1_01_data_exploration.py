def as_tensor(x):
    return x if torch.is_tensor(x) else x.pooler_output

def extract(model_id, paths, bs=32):
    m = CLIPModel.from_pretrained(model_id).to(device).eval()
    proc = CLIPProcessor.from_pretrained(model_id)
    out = []
    with torch.no_grad():
        for i in tqdm(range(0, len(paths), bs), desc=model_id):
            imgs = [ImageOps.exif_transpose(Image.open(p)).convert("RGB") for p in paths[i:i+bs]]
            inp = proc(images=imgs, return_tensors="pt").to(device)
            f = as_tensor(m.get_image_features(**inp))
            out.append((f / f.norm(dim=-1, keepdim=True)).cpu())
    del m; gc.collect(); torch.cuda.empty_cache()
    return torch.cat(out).numpy()

