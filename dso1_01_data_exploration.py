@torch.no_grad()
def image_features(paths, bs=32):
    out = []
    for i in tqdm(range(0, len(paths), bs)):
        imgs = [ImageOps.exif_transpose(Image.open(p)).convert("RGB") for p in paths[i:i+bs]]
        inp = processor(images=imgs, return_tensors="pt").to(device)
        f = as_tensor(model.get_image_features(**inp))
        f = f / f.norm(dim=-1, keepdim=True)
        out.append(f.cpu())
    return torch.cat(out)

