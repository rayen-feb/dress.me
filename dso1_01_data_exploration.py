def upscaled_bytes(p, side=256):
    im = Image.open(p).convert("RGB")
    s = side / min(im.size)
    im = im.resize((round(im.width * s), round(im.height * s)), Image.BICUBIC)
    buf = io.BytesIO(); im.save(buf, format="PNG")
    return buf.getvalue()

